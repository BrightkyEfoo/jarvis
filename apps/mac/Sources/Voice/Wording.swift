import Foundation

/// Tool summaries are written in English for the audit log. This turns them into French for the
/// dashboard and the voice. Specific patterns come before general ones.
enum Wording {
    private static let rules: [(String, String)] = [
        (#"^Send from (\S+) to (\S+) — "([^"]*)":"#, "Envoyer depuis $1 à $2, objet « $3 » :"),
        (#"^Send from (\S+) to (\S+) — "([^"]*)"$"#, "Envoyer depuis $1 à $2, objet « $3 »"),
        (#"^Send to (\S+) — "([^"]*)":"#, "Envoyer à $1, objet « $2 » :"),
        (#"^Send draft (\S+) from (\S+)"#, "Envoyer le brouillon $1 depuis $2"),
        (#"^Draft \((\S+)\) to (\S+) — "([^"]*)""#, "Brouillon ($1) pour $2 — « $3 »"),
        (#"^Morning briefing$"#, "Briefing du matin"),
        (#"^Web research \(quick\): "#, "Recherche web (rapide) : "),
        (#"^Web research \(deep\): "#, "Recherche web (approfondie) : "),
        (#"^YouTube search: "#, "Recherche YouTube : "),
        (#"^Watch video "#, "Regarder la vidéo "),
        (#"^Triage mail (.+) \((\d+) h\)"#, "Tri des mails : $1 ($2 h)"),
        (#"^Read mail "#, "Lire le mail "),
        (#"^Read calendar \(today\)"#, "Agenda du jour"),
        (#"^Read calendar \(tomorrow\)"#, "Agenda de demain"),
        (#"^Read calendar \(week\)"#, "Agenda de la semaine"),
        (#"^Read the clock$"#, "Lire l'heure"),
        (#"^Read system status$"#, "État du Mac"),
        (#"^Click (\S+) "([^"]*)" on (\S+)$"#, "Cliquer sur « $2 » ($1) sur $3"),
        (#"^Click (\S+) "([^"]*)" in (.+)$"#, "Cliquer sur « $2 » dans $3"),
        (#"^Click (.*) in (.+)$"#, "Cliquer $1 dans $2"),
        (#"^Double-click (.*) in (.+)$"#, "Double-cliquer $1 dans $2"),
        (#"^Type "([^"]*)" into (\S+) "([^"]*)" on (\S+)$"#, "Taper « $1 » dans « $3 » sur $4"),
        (#"^Type "([^"]*)" in (.+?) into (.+)$"#, "Taper « $1 » dans $2 ($3)"),
        (#"^Type "([^"]*)" in (.+)$"#, "Taper « $1 » dans $2"),
        (#"^Press (\S+) in (.+)$"#, "Appuyer sur $1 dans $2"),
        (#"^Scroll (-?\d+) in (.+)$"#, "Défiler de $1 dans $2"),
        (#"^Open (\S+) in (Arc|Google Chrome)$"#, "Ouvrir $1 dans $2"),
        (#"^Read the active (.+) tab.*$"#, "Lire l'onglet actif de $1"),
        (#"^List (Arc|Google Chrome) tabs$"#, "Onglets de $1"),
        (#"^Back in "#, "Retour dans "),
        (#"^Look at the frontmost app$"#, "Regarder l'app au premier plan"),
        (#"^Look at "#, "Regarder "),
        (#"^Create note "([^"]*)""#, "Créer la note « $1 »"),
        (#"^Add reminder "([^"]*)" for (.+)$"#, "Rappel « $1 » pour $2"),
        (#"^Add reminder "([^"]*)""#, "Ajouter le rappel « $1 »"),
        (#"^Complete a reminder$"#, "Cocher un rappel"),
        (#"^Read a note$"#, "Lire une note"),
        (#"^Take up to (\d+) Trello cards labelled ([^:\s]+).*$"#, "Prendre jusqu'à $1 cartes Trello « $2 » : un worker par carte, carte en cours puis lien de la PR et carte à relire"),
        (#"^Start a worker on (\S+): "#, "Lancer un worker sur $1 : "),
        (#"^Workers status$"#, "État des workers"),
        (#"^Cancel worker task "#, "Annuler la tâche "),
        (#"^Read worker log "#, "Journal du worker "),
        (#"^Forge inbox \(GitHub/GitLab\)$"#, "Ce qui m'attend sur GitHub et GitLab"),
        (#"^Read PR (\S+)$"#, "Lire la PR $1"),
        (#"^Read issue (\S+)$"#, "Lire l'issue $1"),
        (#"^List PRs of "#, "Lister les PR de "),
        (#"^List PRs$"#, "Lister les PR"),
        (#"^Comment on (?:github|gitlab|forge) (\S+): "#, "Commenter $1 : "),
        (#"^Comment on Trello card \S+: "#, "Commenter la carte Trello : "),
        (#"^Move Trello card \S+ to list \S+$"#, "Déplacer la carte Trello"),
        (#"^List Trello cards labelled "#, "Cartes Trello étiquetées "),
        (#"^List Trello cards$"#, "Cartes Trello"),
        (#"^List Trello boards$"#, "Tableaux Trello"),
        (#"^Read a Trello card$"#, "Lire une carte Trello"),
        (#"^List open apps$"#, "Apps ouvertes"),
        (#"^List shortcuts$"#, "Raccourcis disponibles"),
        (#"^List projects"#, "Lister les projets"),
        (#"^List "#, "Lister "),
        (#"^Read "#, "Lire "),
        (#"^Write (\d+) chars to "#, "Écrire $1 caractères dans "),
        (#"^Append (\d+) chars to "#, "Ajouter $1 caractères à "),
        (#"^Search memory for "#, "Chercher en mémoire : "),
